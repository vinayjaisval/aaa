                    <p>
                        <ul style="padding-left:25px">
                            <li>•   Data security policies relating to the network, database and applications in place; </li>
                            <li>• Data loss prevention measures deployed; </li>
                            <li>• Effective network access controls implemented; </li>
                            <li>• Detection/prevention systems deployed; </li>
                            <li>• Security controls established (physical and logical); </li>
                            <li>• Incident response program implemented.</li>
